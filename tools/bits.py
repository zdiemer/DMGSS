"""Original CB diagnostic. Only assemble bytes; the browser executes the ROM."""


def bits_rom():
    code, checks = [], []
    def emit(*values):
        code.extend(values)
    def check(opcode=0xC2):
        emit(opcode, 0, 0)
        checks.append(len(code)-2)
    emit(0x21,0,0xC0,0x36,0x81)
    # RAM: rotate through carry, signed/unsigned shifts, nibble swap, SET/RES.
    for opcode in (0x06,0x1E,0x2E,0x3E,0x26,0x36,0xCE,0x8E):
        emit(0xCB,opcode)
    emit(0xCB,0x66); check()  # BIT 4 must be zero, memory remains 0C.
    emit(0x7E,0xFE,0x0C); check()
    emit(0x06,0x81,0xCB,0x00,0xCB,0x08,0x37)
    for opcode in (0x10,0x18,0x20,0x28,0x30,0x38,0xF8,0x80):
        emit(0xCB,opcode)
    emit(0xCB,0x78); check(0xCA)  # BIT 7 must be set.
    emit(0x78,0xFE,0x88); check()
    emit(0x21,0,0x80,0x36,0xF0,0xCB,0x36,0x7E,0xFE,0x0F); check()
    emit(0x3E,0xA5,0xEA,2,0xC0,0x76)
    failure = 0x100 + len(code)
    emit(0x3E,0xFF,0xEA,2,0xC0,0x76)
    for index in checks:
        code[index:index+2] = [failure % 256, failure // 256]
    return code
