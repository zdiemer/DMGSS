"""Original timer/HALT diagnostic assembly. Execution remains in CSS."""
from rom import ROM


def timer_rom():
    data=bytearray(32768)
    data[0x100:0x103]=bytes([0xC3,0x50,1])
    # Record TIMA after the hardware request, disable the timer and return.
    data[0x50:0x5A]=bytes([0x04,0xF0,5,0xEA,0,0xC0,0xAF,0xE0,7,0xD9])
    code,checks=[],[]
    def emit(*values): code.extend(values)
    def check():
        emit(0xC2,0,0);checks.append(len(code)-2)
    emit(0x31,0xFE,0xFF,0xF3,0xAF,0xE0,15,0x3E,4,0xE0,255)
    emit(0x3E,42,0xE0,6,0x3E,0xFC,0xE0,5,0xAF,0xE0,4)
    emit(0x3E,6,0xE0,7,0xFB,0,0x76)
    emit(0x78,0xFE,1);check()
    emit(0xFA,0,0xC0,0xFE,42);check()
    emit(0xF0,7,0xFE,0xF8);check()
    emit(0x3E,0xA5,0xEA,2,0xC0,0x76)
    failure=0x150+len(code)
    emit(0xAF,0xE0,7,0x3E,0xFF,0xEA,2,0xC0,0x76)
    for index in checks:code[index:index+2]=[failure%256,failure//256]
    data[0x150:0x150+len(code)]=bytes(code)
    return ROM(data,base=0)
