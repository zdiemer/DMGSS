"""Assemble original restart/HRAM diagnostics. No CPU execution in Python."""
from rom import ROM


def high_rom():
    data = bytearray(32768)
    data[0x100:0x103] = bytes([0xC3,0x50,1])
    for vector in range(0,0x40,8):
        data[vector:vector+2] = bytes([0x3C,0xC9])  # INC A; RET
    code, checks = [], []
    def emit(*values):
        code.extend(values)
    def check():
        emit(0xC2,0,0)
        checks.append(len(code)-2)
    emit(0x31,0xFE,0xFF,0x3E,0)
    for vector in range(0,0x40,8):
        emit(0xC7+vector)
    emit(0xFE,8); check()
    emit(0xE0,0x80,0xAF,0xF0,0x80,0x0E,0xFE,0xE2,0xAF,0xF2,0xFE,8); check()
    # Write LD A,42; RET into HRAM, then call the bytes just written.
    emit(0x21,0x90,0xFF,0x36,0x3E,0x23,0x36,42,0x23,0x36,0xC9,0xCD,0x90,0xFF,0xFE,42); check()
    emit(0x08,0xFC,0xFF,0xF0,0xFC,0xFE,0xFE); check()
    emit(0xF0,0xFD,0xFE,0xFF); check()
    emit(0x3E,0xA5,0xEA,2,0xC0,0x76)
    failure = 0x150 + len(code)
    emit(0x3E,0xFF,0xEA,2,0xC0,0x76)
    for index in checks:
        code[index:index+2] = [failure % 256, failure // 256]
    data[0x150:0x150+len(code)] = bytes(code)
    return ROM(data, base=0)


def high_continuation():
    data = bytearray(0x100)
    data[0:7] = bytes([0xF0,0x80,0xCB,0x07,0xE0,0xFE,0xC9])
    # Instruction 128 is RST 00. Its live HRAM return address crosses the bank.
    data.extend([0x31,0xFE,0xFF,0x3E,0x81,0xE0,0x80,0x0E,0xFE,0xE2] + [0]*122 + [0xC7,0x76])
    return ROM(data, base=0)


def high_fill():
    return [0x3E,0x5A] + [byte for offset in range(0x80,0xFF) for byte in (0xE0,offset)] + [0x76]
