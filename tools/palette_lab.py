"""Original palette lab ROM assembly. CPU execution remains entirely in CSS."""
from cpu import tile_data


def palette_rom():
    # Copy the tile with an identity palette, wait across a 128-stage bank,
    # then reverse the palette without rewriting any tile bytes. Read it back.
    code = [0x3E,0xE4,0xE0,0x47,0x21,0,0,0x11,0,0x80,0x06,16,
            0x2A,0x12,0x13,0x05,0x20,0xFA,
            0x06,24,0x05,0x20,0xFD,
            0x3E,0x1B,0xE0,0x47,0xF0,0x47,0xFE,0x1B,0x20,7,
            0x3E,0xA5,0xEA,2,0xC0,0x76,0xD3,
            0x3E,0xFF,0xEA,2,0xC0,0x76]
    address = 0x100 + len(code)
    code[5:7] = [address & 255,address >> 8]
    return code + tile_data()
