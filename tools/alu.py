"""Original self-checking ALU cartridge. Assembly only; CPU work runs in CSS."""


def alu_rom():
    code, checks = [], []
    def emit(*values):
        code.extend(values)
    def check(opcode=0xC2):
        emit(opcode, 0, 0)
        checks.append(len(code)-2)
    emit(0x31,0x40,0xC0,0x3E,0x99,0xC6,1,0x27)  # BCD 99 + 1 = 00, carry.
    check(); check(0xD2)
    emit(0x06,1,0x88,0xFE,2)  # ADC A,B includes the decimal carry.
    check()
    emit(0x37,0x98)  # SBC A,B: 2 - 1 - carry = 0.
    check()
    emit(0x3E,0x0F,0x2F,0x06,0xAA,0xA0,0xEE,0x0F,0xF6,0x50,0xFE,0xFF)
    check()
    emit(0x3E,0x81,0x07,0x1F,0x0F,0x17,0xFE,0x81)
    check()
    emit(0x3F)  # CP cleared carry; CCF must set it.
    check(0xD2)
    emit(0x3E,0x42,0xD6,2,0x27,0xFE,0x40)  # Subtraction-mode DAA.
    check()
    emit(0x21,0,0xC0,0x36,0x10,0x86,0xFE,0x50)
    check()
    emit(0x3E,0xA5,0xEA,2,0xC0,0x76)
    fail = 256 + len(code)
    emit(0x3E,0xFF,0xEA,2,0xC0,0x76)
    for address in checks:
        code[address:address+2] = [fail % 256, fail // 256]
    return code
