"""Original ROM-only MBC1 sample; this builds bytes, never executes them."""


def sample_rom():
    data = bytearray(65536)
    data[0x100:0x103] = bytes([0xC3, 0x50, 1])
    data[0x134:0x13E] = b'DMGSS MBC1'
    data[0x147:0x14A] = bytes([1, 1, 0])
    # Call code in bank 2, then select bank 0 (which maps to bank 1).
    code = [0x31,0,0xC1,0x3E,2,0xEA,0,0x20,0xCD,0,0x40,
            0xEA,0,0xC0,0xAF,0xEA,0,0x20,0xFA,0,0x41,0xEA,1,0xC0,0x76]
    data[0x150:0x150+len(code)] = bytes(code)
    data[0x8000:0x8003] = bytes([0x3E,42,0xC9])
    data[0x4100] = 17
    data[0x14D] = (-sum(data[0x134:0x14D])-25) & 255
    data[0x14E:0x150] = ((sum(data[:0x14E])+sum(data[0x150:])) & 65535).to_bytes(2,'big')
    return bytes(data)
