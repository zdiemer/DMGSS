const {readState}=require('./helpers/state');
const {test,expect}=require('@playwright/test');
const read = page => readState(page,['pc','ticks','a','b','h','l','f','m32768','m49152','m49154','halted','fault']);
for(const mode of ['portable','automatic','checkpoint','streaming'])test(`Bit lab checks CB register and memory operations in ${mode}`,async({page},info)=>{
  test.skip(mode==='streaming'&&info.project.name==='webkit-mobile','Streaming requires Chromium');
  if(mode==='streaming')test.setTimeout(300000);
  const prefix=mode==='streaming'?'':`/${mode}`;
  await page.goto(`${prefix}/`);
  await page.getByRole('link',{name:'Bit lab',exact:true}).click();
  await expect(page).toHaveURL(new RegExp(`${prefix}/bits/$`));
  await page.locator('.power-switch').click();
  await expect.poll(async()=>(await read(page)).halted,{timeout:mode==='streaming'?180000:20000}).toBe(1);
  const result=await read(page);
  expect(result).toEqual({pc:341,ticks:41,a:165,b:136,h:128,l:0,f:192,m32768:15,m49152:12,m49154:165,halted:1,fault:0});
  await expect(page.locator('.passed')).toBeVisible();
  await page.setViewportSize({width:320,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  expect(await page.locator('.cartridges').evaluate(el=>el.scrollWidth<=el.clientWidth)).toBe(true);
  await expect(page.locator('.cartridges [aria-current="page"]')).toHaveText('Bit lab');
  await page.screenshot({path:info.outputPath('bit-lab.png'),fullPage:true});
});
